export const OPERATORS: CalibOp[] = ['=', '!=', '>', '>=', '<', '<=', 'IN'];

export function severityColor(s: ValidationIssue['severity']): string {
  return s === 'BLOCKER' ? 'red' : s === 'WARNING' ? 'orange' : 'blue';
}

export function caliberSummary(f?: CaliberFilter): string {
  if (!f || f.conditions.length === 0) return '-（全部数据，无口径）';
  return f.conditions
    .map((c) => `${c.attributeCode} ${c.op} ${c.op === 'IN' ? `(${c.values.join(',')})` : c.values[0] ?? ''}`)
    .join(` ${f.logic} `);
}

export function targetObjectLabel(t: TargetObjectType): string {
  return t === 'METRIC' ? '指标' : t === 'ENTITY' ? '实体' : '事件';
}

/* 取某对象（实体或事件）的可筛选属性，供 FILTER 条件构建器 */
export function filterableAttrs(objType: TargetObjectType, objId: number): ObjAttribute[] {
  if (objType === 'ENTITY') return mockEntities.find((e) => e.id === objId)?.attributes.filter((a) => a.isFilterable) ?? [];
  if (objType === 'EVENT') return mockEvents.find((e) => e.id === objId)?.attributes.filter((a) => a.isFilterable) ?? [];
  return [];
}

export type Metric2WorkspaceData = {
  events: SemanticEvent[];
  entities: SemanticEntity[];
  relations: SemanticRelation[];
  metrics: SemanticMetric[];
  rules: BusinessRule[];
  ruleCandidates?: ReadOnlyRuleCandidate[];
  targets: MetricTarget[];
};

const originalMetric2Data: Metric2WorkspaceData = structuredClone({
  events: mockEvents,
  entities: mockEntities,
  relations: mockRelations,
  metrics: mockMetrics,
  rules: mockRules,
  targets: mockTargets,
});
let currentRuleCandidates: ReadOnlyRuleCandidate[] = [];

export function normalizeMetric2WorkspaceData(data: Metric2WorkspaceData): Metric2WorkspaceData {
  const source = structuredClone(data);
  const legacyCandidates = source.rules.filter((rule) => rule.description?.startsWith('待结构化规则候选：'));
  source.rules = source.rules.filter((rule) => !legacyCandidates.includes(rule));
  if (!source.ruleCandidates?.length && legacyCandidates.length) {
    source.ruleCandidates = legacyCandidates.map((rule) => ({
      id: rule.id,
      ruleCode: rule.ruleCode || `legacy-rule-${rule.id}`,
      ruleName: rule.ruleName || '历史规则候选',
      description: rule.description?.replace(/^待结构化规则候选：/, '') || '历史候选内容未完整保留。',
      evidenceRefs: [],
      status: 'UNRESOLVED_TARGET',
    }));
  }
  source.ruleCandidates ??= [];
  return source;
}

export function replaceMetric2WorkspaceData(data?: Metric2WorkspaceData) {
  const source = normalizeMetric2WorkspaceData(data ?? originalMetric2Data);
  mockEvents.splice(0, mockEvents.length, ...structuredClone(source.events));
  mockEntities.splice(0, mockEntities.length, ...structuredClone(source.entities));
  mockRelations.splice(0, mockRelations.length, ...structuredClone(source.relations));
  mockMetrics.splice(0, mockMetrics.length, ...structuredClone(source.metrics));
  mockRules.splice(0, mockRules.length, ...structuredClone(source.rules));
  currentRuleCandidates = structuredClone(source.ruleCandidates ?? []);
  mockTargets.splice(0, mockTargets.length, ...structuredClone(source.targets));
}

export function readMetric2WorkspaceData(): Metric2WorkspaceData {
  return structuredClone({
    events: mockEvents, entities: mockEntities, relations: mockRelations,
    metrics: mockMetrics, rules: mockRules, ruleCandidates: currentRuleCandidates, targets: mockTargets,
  });
}


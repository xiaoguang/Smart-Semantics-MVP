/* 从某 event 出发 BFS 可达实体（用于目标值 dimension_filter） */
export function reachableEntities(eventId: number): SemanticEntity[] {
  const visited = new Set<number>();
  const queue: { id: number; type: 'EVENT' | 'ENTITY' }[] = [{ id: eventId, type: 'EVENT' }];
  const result: SemanticEntity[] = [];
  while (queue.length) {
    const node = queue.shift()!;
    for (const r of mockRelations) {
      if (r.sourceType === node.type && r.sourceId === node.id && !visited.has(r.targetId)) {
        visited.add(r.targetId);
        const ent = mockEntities.find((e) => e.id === r.targetId);
        if (ent) result.push(ent);
        queue.push({ id: r.targetId, type: 'ENTITY' });
      }
    }
  }
  return result;
}

export function metricRootEventId(m: SemanticMetric): number | undefined {
  if (m.metricType === 'BASIC') return m.eventId;
  if (m.formulaTokens) {
    for (const token of m.formulaTokens) {
      if (token.type !== 'METRIC') continue;
      const ref = mockMetrics.find((x) => x.id === token.metricId || x.metricCode === token.metricCode);
      if (ref?.eventId) return ref.eventId;
    }
  }
  if (m.formula) {
    const codes = m.formula.match(/[a-z_]+/g) || [];
    for (const code of codes) {
      const ref = mockMetrics.find((x) => x.metricCode === code);
      if (ref?.eventId) return ref.eventId;
    }
  }
  return undefined;
}


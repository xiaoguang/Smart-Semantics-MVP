import type { ReactNode } from 'react';

/* ============ 基础枚举 ============ */
export type MetricType = 'BASIC' | 'COMPOSITE';
export type RuleMode = 'COMPARISON' | 'FILTER' | 'COMPOSITE';
export type TargetObjectType = 'METRIC' | 'ENTITY' | 'EVENT';
export type CalibOp = '=' | '!=' | '>' | '>=' | '<' | '<=' | 'IN';
export type LogicOp = 'AND' | 'OR';
export type TargetType = 'AMOUNT' | 'RATIO';
export type TimePeriod = 'MONTHLY' | 'QUARTERLY' | 'YEARLY';
export type Status = 'ACTIVE' | 'INACTIVE';

/* ============ 事件 / 实体 / 关系 ============ */
export interface ObjAttribute {
  attributeCode: string;
  attributeName: string;
  dataType: 'STRING' | 'NUMBER' | 'DECIMAL' | 'DATETIME' | 'ENUM' | 'BOOLEAN';
  semanticType: 'IDENTIFIER' | 'DIMENSION' | 'MEASURE' | 'TIME' | 'TEXT';
  isFilterable: boolean;
  isMetric?: boolean;
  aggregateOperator?: 'SUM' | 'COUNT' | 'AVG' | 'MAX' | 'MIN';
  enumValues?: string[];
}

export interface SemanticEvent {
  id: number;
  eventCode: string;
  eventName: string;
  attributes: ObjAttribute[];
}

export interface SemanticEntity {
  id: number;
  entityCode: string;
  entityName: string;
  attributes: ObjAttribute[];
}

export interface SemanticRelation {
  id: number;
  sourceType: 'EVENT' | 'ENTITY';
  sourceId: number;
  targetType: 'EVENT' | 'ENTITY';
  targetId: number;
  relationRole: string;
}

/* ============ 条件（单对象属性条件，caliber_filter 与 FILTER 共用） ============ */
export interface CaliberCondition {
  attributeCode: string;
  attributeName?: string;
  op: CalibOp;
  values: string[];
}
export interface CaliberFilter {
  logic: LogicOp;
  conditions: CaliberCondition[];
}

export type FormulaTokenType = 'METRIC' | 'OP' | 'NUM' | 'LPAREN' | 'RPAREN';
export type FormulaOperator = '+' | '-' | '*' | '/';

export interface FormulaToken {
  type: FormulaTokenType;
  value: string;
  metricId?: number;
  metricCode?: string;
  metricName?: string;
}

export type FormulaExpression =
  | { type: 'METRIC'; metricId: number; metricCode: string }
  | { type: 'NUMBER'; value: number }
  | { type: 'BINARY'; operator: FormulaOperator; left: FormulaExpression; right: FormulaExpression };

export interface ComparisonExpression {
  operator: '<' | '<=' | '>' | '>=' | '=' | '!=';
  ratio?: number; // 达成线，默认 1：actual (operator) (target_value * ratio)
}

export interface CompositeComponent {
  subRuleId: number;
  isNegated: boolean;
  sortOrder: number;
}

/* ============ 指标 ============ */
export interface SemanticMetric {
  id: number;
  metricCode: string;
  metricName: string;
  metricType: MetricType;
  unit?: string;
  description?: string;
  eventId?: number;
  eventName?: string;
  baseAttributeCode?: string;
  defaultOperator?: string;
  caliberFilter?: CaliberFilter;
  formula?: string;
  formulaTokens?: FormulaToken[];
  formulaExpression?: FormulaExpression;
  editability?: 'EDITABLE' | 'READ_ONLY';
  compatibilityReason?: string;
  isAutoGenerated: boolean;
  status: Status;
}

/* ============ 业务规则（三模式，每条挂一个语义对象） ============ */
export interface BusinessRule {
  id: number;
  ruleCode: string;
  ruleName: string;
  ruleType: RuleMode;
  targetObjectType: TargetObjectType;
  targetObjectId: number;
  targetObjectName: string;
  expression: ComparisonExpression | CaliberFilter | null; // COMPARISON | FILTER | null(COMPOSITE)
  logicOperator?: LogicOp;
  components?: CompositeComponent[];
  isNegative: boolean;
  oppositeRuleId?: number;
  triggerWords: string[];
  description?: string;
  status: Status;
}

export interface ReadOnlyRuleCandidate {
  id: number;
  ruleCode: string;
  ruleName: string;
  description: string;
  targetObjectType?: TargetObjectType;
  targetObjectId?: number;
  targetObjectName?: string;
  evidenceRefs: string[];
  status: 'NEEDS_STRUCTURE' | 'UNRESOLVED_TARGET';
}

/* ============ 目标值 ============ */
export interface DimensionItem {
  entityCode: string;
  valueCode: string;
}
export interface DimensionFilter {
  dimensions: DimensionItem[];
}
export interface MetricTarget {
  id: number;
  metricId: number;
  metricName: string;
  targetType: TargetType;
  targetValue: number;
  dimensionFilter: DimensionFilter;
  timePeriod: TimePeriod;
  effectiveDate: string;
  description?: string;
  status: Status;
}

export interface ValidationIssue {
  severity: 'BLOCKER' | 'WARNING' | 'INFO';
  checkCode: string;
  message: string;
}


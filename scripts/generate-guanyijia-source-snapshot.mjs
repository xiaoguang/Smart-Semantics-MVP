import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createGuanyijiaStandardizationStory } from '../src/features/guanyijia-standardization-story/index.ts';
import { defaultGuanyijiaPolicyDocuments } from '../src/features/guanyijia-standardization-story/policy-documents.ts';
import { sha256HexSync } from '../src/features/ai-modeling/sha256.ts';
import { canonicalModelingJson } from '../src/features/modeling-document-bridge/standard-markdown.ts';

// Passing an explicit copy is the one maintenance-only route that invokes the
// compiler. Normal application code calls the default story and therefore
// reads the checked-in bundle rather than scanning or recompiling sources.
const story = createGuanyijiaStandardizationStory({
  policyDocuments: structuredClone(defaultGuanyijiaPolicyDocuments),
});
const sources = story.listSources();
const compilations = [];
for (const source of sources) {
  compilations.push(story.compileSource({ sourceId: source.sourceId, priorCompilations: compilations }));
}

const core = {
  schemaVersion: 1,
  storyKey: 'guanyijia-five-source-v1',
  compilerVersion: 'content-first-v1',
  sourceIdentities: sources,
  compilations,
};
const bundle = {
  ...core,
  bundleSha256: `sha256:${sha256HexSync(canonicalModelingJson(core))}`,
};
const output = resolve('src/features/guanyijia-standardization-story/pinned-source-snapshot.generated.ts');
writeFileSync(output, [
  '/* This file is generated by npm run snapshot:guanyijia:refresh. */',
  "import type { PinnedSourceSnapshotCore } from './pinned-source-snapshot.ts';",
  '',
  `export const pinnedGuanyijiaFiveSourceSnapshotCore: PinnedSourceSnapshotCore = ${JSON.stringify(bundle, null, 2)};`,
  '',
].join('\n'));
